def run_collector(fixture, outdir, *, as_of=iso(120), delegation="deleg_synthetic01", extra=()):
    command = [
        sys.executable,
        str(COLLECTOR),
        "--manifest",
        str(fixture["manifest"]),
        "--delegation-id",
        delegation,
        "--state-db",
        str(fixture["db"]),
        "--output",
        str(outdir),
        "--as-of",
        as_of,
        "--commands",
        str(fixture["ledger"]),
        "--coordinator-events",
        str(fixture["events"]),
        "--roster",
        str(fixture["roster"]),
    ]
    command.extend(extra)
    return subprocess.run(command, capture_output=True, text=True, cwd=str(REPO), timeout=120)


def read_all(directory):
    return "\n".join(
        path.read_text(encoding="utf-8") for path in sorted(Path(directory).iterdir()) if path.is_file()
    )


class SyntheticFixtureTests(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="obs-selftest-"))
        self.addCleanup(shutil.rmtree, self.tmp, ignore_errors=True)

    def test_overlapping_intervals_are_not_additive(self):
        fixture = build_fixture(self.tmp / "case")
        proc = run_collector(fixture, self.tmp / "out")
        self.assertEqual(proc.returncode, 0, proc.stderr)
        run = json.loads((self.tmp / "out" / "run.json").read_text(encoding="utf-8"))
        concurrency = run["concurrency"]
        # [10,40] [20,60] [35,50] [70,100 open]
        self.assertAlmostEqual(concurrency["overlapping_sum_seconds_not_additive"], 115.0, places=6)
        self.assertAlmostEqual(concurrency["union_seconds"], 50.0 + 30.0, places=6)
        self.assertEqual(concurrency["peak_concurrent_workers"], 3)
        # The union is strictly less than the naive sum, and that difference is
        # not reported as saved time anywhere.
        self.assertLess(concurrency["union_seconds"], concurrency["overlapping_sum_seconds_not_additive"])
        self.assertNotIn("speedup", read_all(self.tmp / "out").lower())

    def test_unfinished_worker_is_open_not_pass(self):
        fixture = build_fixture(self.tmp / "case")
        proc = run_collector(fixture, self.tmp / "out")
        self.assertEqual(proc.returncode, 0, proc.stderr)
        run = json.loads((self.tmp / "out" / "run.json").read_text(encoding="utf-8"))
        open_workers = [w for w in run["workers"] if w["interval_status"] == "open_at_snapshot"]
        self.assertEqual(len(open_workers), 1)
        self.assertIsNone(open_workers[0]["ended_at_utc"])
        events = (self.tmp / "out" / "events.jsonl").read_text(encoding="utf-8").splitlines()
        self.assertTrue(any("worker_still_running_at_snapshot" in line for line in events))
        self.assertFalse(any('"type": "worker_end"' in line for line in events if open_workers[0]["pseudonym"] in line))
        self.assertEqual(run["delivery_status"], "draft_snapshot")
        self.assertFalse(run["accepted"])
        self.assertIsNone(run["cost"]["usd"])
        self.assertIsNone(run["tokens"]["billable"])
        self.assertEqual(run["review"]["status"], "pending")

    def test_running_delegation_reports_lower_bound_wall(self):
        fixture = build_fixture(self.tmp / "case", with_result=False)
        conn = sqlite3.connect(fixture["db"])
        conn.execute("UPDATE async_delegations SET state='running', completed_at=NULL")
        conn.commit()
        conn.close()
        proc = run_collector(fixture, self.tmp / "out")
        self.assertEqual(proc.returncode, 0, proc.stderr)
        run = json.loads((self.tmp / "out" / "run.json").read_text(encoding="utf-8"))
        self.assertTrue(run["stage_window"]["lower_bound"])
        self.assertFalse(run["stage_window"]["completed"])
        self.assertFalse(run["delegation"]["completed_at_utc"])
        self.assertTrue(any("lower bounds" in gap for gap in run["gaps"]))
        self.assertEqual(run["commands"]["verdict"], "partial_observation")
        self.assertEqual(run["commands"]["incomplete_records"], 1)
        self.assertEqual(run["commands"]["nonzero"], 0)

    def test_missing_columns_are_gaps_not_crashes(self):
        fixture = build_fixture(
            self.tmp / "case", drop_columns=("api_call_count", "cache_read_tokens", "end_reason")
        )
        proc = run_collector(fixture, self.tmp / "out")
        self.assertEqual(proc.returncode, 0, proc.stderr)
        run = json.loads((self.tmp / "out" / "run.json").read_text(encoding="utf-8"))
        self.assertTrue(any("sessions columns absent" in gap for gap in run["gaps"]))
        self.assertTrue(all(worker["api_calls"] is None for worker in run["workers"]))

    def test_absent_delegation_fails_instead_of_completing(self):
        fixture = build_fixture(self.tmp / "case")
        proc = run_collector(fixture, self.tmp / "out", delegation="deleg_does_not_exist")
        self.assertEqual(proc.returncode, 2, proc.stderr)
        self.assertIn("not treated as completion", proc.stderr)
        self.assertFalse((self.tmp / "out" / "run.json").exists())

    def test_sanitization_removes_paths_and_secrets(self):
        fixture = build_fixture(self.tmp / "case")
        proc = run_collector(fixture, self.tmp / "out")
        self.assertEqual(proc.returncode, 0, proc.stderr)
        blob = read_all(self.tmp / "out")
        for secret in SECRETS:
            self.assertNotIn(secret, blob, "leaked: %s" % secret)
        self.assertNotIn("synthetic_session_", blob)
        self.assertIn("<private-run-dir>", blob)
        self.assertIn("<user-home>", blob)
        self.assertIn("draft_snapshot", blob)
        # Pseudonyms stay stable and one-way linkable for the coordinator.
        run = json.loads((self.tmp / "out" / "run.json").read_text(encoding="utf-8"))
        expected = hashlib.sha256(b"synthetic_session_aaa").hexdigest()
        self.assertEqual(run["workers"][0]["identity_sha256"], expected)

    def test_deterministic_bytes_for_frozen_input(self):
        fixture = build_fixture(self.tmp / "case")
        first, second = self.tmp / "out1", self.tmp / "out2"
        self.assertEqual(run_collector(fixture, first).returncode, 0)
        self.assertEqual(run_collector(fixture, second).returncode, 0)
        names = sorted(path.name for path in first.iterdir())
        self.assertEqual(names, sorted(["commands.txt", "events.jsonl", "provenance.json", "run.json", "workers.json"]))
        for name in names:
            self.assertEqual(
                hashlib.sha256((first / name).read_bytes()).hexdigest(),
                hashlib.sha256((second / name).read_bytes()).hexdigest(),
                "non-deterministic output: %s" % name,
            )


class PublishedTreeTests(unittest.TestCase):
    """Integrity of the published docs and metrics tree (real R1 artifacts)."""

    def test_docs_links_resolve(self):
        if not DOCS.is_dir():
            self.skipTest("docs/observability not present")
        docs = sorted(DOCS.glob("*.md"))
        self.assertTrue(docs, "no observability docs")
        for doc in docs:
            text = doc.read_text(encoding="utf-8")
            for target in re.findall(r"\]\(([^)]+)\)", text):
                if target.startswith(("http://", "https://", "#", "mailto:")):
                    continue
                path = target.split("#", 1)[0]
                self.assertTrue(path, "empty link in %s" % doc.name)
                resolved = (doc.parent / path).resolve()
                self.assertTrue(resolved.exists(), "%s links to missing %s" % (doc.name, target))

    def test_published_hashes_match_provenance(self):
        provenance_path = METRICS / "provenance.json"
        if not provenance_path.is_file():
            self.skipTest("metrics provenance not present")
        provenance = json.loads(provenance_path.read_text(encoding="utf-8"))
        recorded = provenance["integrity"]["output_sha256"]
        self.assertEqual(set(recorded), {"run.json", "workers.json", "events.jsonl", "commands.txt"})
        for name, digest in recorded.items():
            actual = hashlib.sha256((METRICS / name).read_bytes()).hexdigest()
            self.assertEqual(actual, digest, "hash mismatch for %s" % name)
        run = json.loads((METRICS / "run.json").read_text(encoding="utf-8"))
        self.assertEqual(run["delivery_status"], "draft_snapshot")
        self.assertFalse(run["accepted"])
        blob = read_all(METRICS)
        self.assertNotIn("C:\\Users", blob)
        self.assertNotIn("C:/Users", blob)


if __name__ == "__main__":
    unittest.main(verbosity=2)
