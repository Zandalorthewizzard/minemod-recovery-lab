#!/usr/bin/env python3
"""Self-test for tools/observability/collect_run.py.

ALL DATA IN THIS FILE IS SYNTHETIC. Fixtures are built inside a temporary
directory, carry a SYNTHETIC-FIXTURE banner, and must never be read as R1
measurements. The test exercises:

  1. overlapping interval arithmetic (naive sum, union, peak) and the fact that
     overlapping durations are not additive;
  2. an unfinished worker at snapshot time -> open interval, never a PASS;
  3. a source schema with absent columns -> recorded gap, null values, no crash;
  4. sanitization of local paths, emails, password-like and token-like strings,
     including session identifiers replaced by pseudonyms;
  5. absent delegation -> explicit failure exit code, not a completion record;
  6. command-ledger validation: a record without an exit code is not a success;
  7. byte-level determinism: two runs over one frozen fixture hash identically;
  8. link integrity of docs/observability/*.md and hash integrity of the
     published metrics directory (skipped only if that directory is absent).

Run: python tools/observability/test_collect_run.py -v
"""

