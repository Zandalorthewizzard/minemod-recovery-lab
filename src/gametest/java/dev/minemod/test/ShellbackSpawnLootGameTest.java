/** GameTests for the shellback's natural spawn, spawn egg and loot table. */
public class ShellbackSpawnLootGameTest {
	private static final BlockState STONE = Blocks.STONE.defaultBlockState();

	@GameTest(maxTicks = 40)
	public void kill_by_player_drops_plate(final GameTestHelper helper) {
		placeFloor(helper);
		ShellbackEntity shellback = spawnShellback(helper, new Vec3(4.0, 1.0, 3.0));
		// The plated front deflects melee, so the mock player hits from behind.
		Player player = spawnPlayer(helper, new Vec3(4.0, 1.0, 1.4));

		boolean hurt = shellback.hurtServer(helper.getLevel(), helper.getLevel().damageSources().playerAttack(player), 100.0F);

		helper.assertTrue(hurt && shellback.isDeadOrDying(), "lethal player damage from behind must kill the shellback");
		helper.assertItemEntityCountIs(ModItems.SHELLBACK_PLATE, new BlockPos(4, 1, 3), 2.0, 1);
		helper.succeed();
	}

	@GameTest(maxTicks = 40)
	public void kill_without_player_no_plate(final GameTestHelper helper) {
		placeFloor(helper);
		ShellbackEntity shellback = spawnShellback(helper, new Vec3(4.0, 1.0, 3.0));

		shellback.kill(helper.getLevel());

		helper.assertTrue(shellback.isDeadOrDying(), "generic kill must kill the shellback");
		helper.assertItemEntityNotPresent(ModItems.SHELLBACK_PLATE, new BlockPos(4, 1, 3), 2.0);
		helper.succeed();
	}

	@GameTest(maxTicks = 40)
	public void spawn_egg_spawns(final GameTestHelper helper) {
		placeFloor(helper);
		Player player = spawnPlayer(helper, new Vec3(4.0, 1.0, 4.0));
		ItemStack egg = new ItemStack(ModSpawnEggs.SHELLBACK_SPAWN_EGG);
		helper.assertTrue(SpawnEggItem.getType(egg) == ModEntities.SHELLBACK, "spawn egg must be bound to the shellback");

		BlockPos clicked = helper.absolutePos(new BlockPos(2, 0, 2));
		BlockHitResult hit = new BlockHitResult(Vec3.atCenterOf(clicked), Direction.UP, clicked, false);
		InteractionResult result = egg.useOn(new UseOnContext(helper.getLevel(), player, InteractionHand.MAIN_HAND, egg, hit));

		helper.assertTrue(result.consumesAction(), "using the spawn egg must succeed, got " + result);
		helper.assertTrue(egg.isEmpty(), "spawn egg stack must be consumed");
		helper.assertEntityPresent(ModEntities.SHELLBACK, new BlockPos(2, 1, 2), 1.5);
		helper.succeed();
	}

	@GameTest(maxTicks = 40)
	public void overworld_biome_has_spawn(final GameTestHelper helper) {
		ServerLevel overworld = helper.getLevel();
		BlockPos pos = helper.absolutePos(new BlockPos(4, 1, 4));
		// The spawn list the game resolves at a position: the biome's environment attribute, which
		// Fabric patches for loaded dimensions. plains is not generated by this flat test world, so
		// real overworld and nether biomes cover the positive and negative cases respectively.
		MobSpawnSettings live = overworld.environmentAttributes().getValue(EnvironmentAttributes.NATURAL_MOB_SPAWNS, pos);
		String biome = overworld.getBiome(pos).unwrapKey().map(key -> key.identifier().toString()).orElse("none");

		helper.assertTrue(monsterEntries(live).size() > 1, "the overworld biome must keep its vanilla monster spawns, biome " + biome);
		Weighted<MobSpawnSettings.SpawnerData> entry = shellbackEntry(live);
		helper.assertTrue(entry != null, "the overworld biome must list minemod:shellback as a MONSTER spawn, biome " + biome);
		helper.assertTrue(entry.weight() == 25, "spawn weight must be 25, was " + entry.weight());
		helper.assertTrue(entry.value().count().minInclusive() == 1 && entry.value().count().maxInclusive() == 2,
				"group size must be 1..2, was " + entry.value().count().minInclusive() + ".." + entry.value().count().maxInclusive());

		Biome wastes = overworld.registryAccess().lookupOrThrow(Registries.BIOME).getValueOrThrow(Biomes.NETHER_WASTES);
		helper.assertFalse(hasShellback(wastes), "minecraft:nether_wastes must not list minemod:shellback");

		ServerLevel nether = overworld.getServer().getLevel(Level.NETHER);
		helper.assertTrue(nether != null, "the game test server must have a nether level");
		BlockPos netherPos = new BlockPos(0, 64, 0);
		String netherBiome = nether.getBiome(netherPos).unwrapKey().map(key -> key.identifier().toString()).orElse("none");
		helper.assertFalse(shellbackEntry(nether.environmentAttributes().getValue(EnvironmentAttributes.NATURAL_MOB_SPAWNS, netherPos)) != null,
				"a loaded nether biome must not list minemod:shellback, was " + netherBiome);
		helper.succeed();
	}

	@GameTest(maxTicks = 40, skyAccess = true)
	public void placement_rule(final GameTestHelper helper) {
		placeFloor(helper);
		ServerLevel level = helper.getLevel();

		helper.assertTrue(SpawnPlacements.getPlacementType(ModEntities.SHELLBACK) == SpawnPlacementTypes.ON_GROUND, "placement must be ON_GROUND");
		helper.assertTrue(SpawnPlacements.getHeightmapType(ModEntities.SHELLBACK) == Heightmap.Types.MOTION_BLOCKING_NO_LEAVES,
				"heightmap must be MOTION_BLOCKING_NO_LEAVES");

		// Open sky: the registered predicate must reject the surface even though it is below y=50.
		BlockPos open = helper.absolutePos(new BlockPos(6, 1, 6));
		helper.assertTrue(level.canSeeSky(open), "the sky access structure must be open above the floor");
		helper.assertFalse(ShellbackSpawning.isUndergroundSpot(ModEntities.SHELLBACK, level, EntitySpawnReason.NATURAL, open, RandomSource.create(1L)),
				"an open sky position must not pass the spawn predicate");

		// Covered dark spot below the Y threshold: real blocks, real sky light, unmodified predicate.
		BlockPos interior = enclose(helper, new BlockPos(2, 1, 2));

		helper.runAfterDelay(2, () -> {
			helper.assertFalse(level.canSeeSky(interior), "the sealed room must not see the sky");
			helper.assertTrue(level.getBrightness(LightLayer.SKY, interior) == 0, "the sealed room must have no sky light");
			helper.assertTrue(level.getMaxLocalRawBrightness(interior) == 0, "the sealed room must be fully dark");
			helper.assertTrue(SpawnPlacements.isSpawnPositionOk(ModEntities.SHELLBACK, level, interior),
					"ON_GROUND placement must accept the stone floor with two clear blocks above");
			helper.assertTrue(SpawnPlacements.checkSpawnRules(ModEntities.SHELLBACK, level, EntitySpawnReason.NATURAL, interior, RandomSource.create(1L)),
					"a dark covered spot below y=50 must pass the registered spawn predicate");

			// The Y bound is exact and light independent; it cannot be reached inside the structure.
			helper.assertTrue(ShellbackSpawning.isUndergroundSpot(ShellbackSpawning.MAX_SPAWN_Y - 1, false), "y=49 covered must be underground");
			helper.assertFalse(ShellbackSpawning.isUndergroundSpot(ShellbackSpawning.MAX_SPAWN_Y, false), "y=50 covered must not be underground");
			helper.assertFalse(ShellbackSpawning.isUndergroundSpot(ShellbackSpawning.MAX_SPAWN_Y + 12, false), "far above must not be underground");
			helper.succeed();
		});
	}

	private static void placeFloor(final GameTestHelper helper) {
		for (int x = 0; x <= 7; x++)
			for (int z = 0; z <= 7; z++)
				helper.setBlock(x, 0, z, STONE);
	}

	/** Seals the cell around {@code interior} with stone, leaving two clear blocks above the floor. */
	private static BlockPos enclose(final GameTestHelper helper, final BlockPos interior) {
		for (int dx = -1; dx <= 1; dx++)
			for (int dz = -1; dz <= 1; dz++)
				for (int dy = 0; dy <= 2; dy++)
					if (dy == 2 || dx != 0 || dz != 0)
						helper.setBlock(interior.offset(dx, dy, dz), STONE);

		return helper.absolutePos(interior);
	}

	private static ShellbackEntity spawnShellback(final GameTestHelper helper, final Vec3 pos) {
		ShellbackEntity shellback = helper.spawnWithNoFreeWill(ModEntities.SHELLBACK, pos);
		shellback.setYRot(0.0F);
		shellback.setYBodyRot(0.0F);
		shellback.setYHeadRot(0.0F);
		return shellback;
	}

	private static Player spawnPlayer(final GameTestHelper helper, final Vec3 pos) {
		Player player = helper.makeMockPlayer(GameType.SURVIVAL);
		Vec3 absolute = helper.absoluteVec(pos);
		player.setPos(absolute.x, absolute.y, absolute.z);
		return player;
	}

	private static List<Weighted<MobSpawnSettings.SpawnerData>> monsterEntries(final MobSpawnSettings settings) {
		return settings.getMobsToSpawn(MobCategory.MONSTER).unwrap();
	}

	private static Weighted<MobSpawnSettings.SpawnerData> shellbackEntry(final MobSpawnSettings settings) {
		return monsterEntries(settings).stream().filter(entry -> entry.value().type() == ModEntities.SHELLBACK).findFirst().orElse(null);
	}

	private static boolean hasShellback(final Biome biome) {
		MobSpawnSettings settings = biome.getAttributes().applyModifier(EnvironmentAttributes.NATURAL_MOB_SPAWNS,
				EnvironmentAttributes.NATURAL_MOB_SPAWNS.defaultValue());
		return shellbackEntry(settings) != null;
	}
}
